    private void prosesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_prosesActionPerformed
        try {
        double input1 = Double.parseDouble(txtAngka1.getText());
        double input2 = Double.parseDouble(txtAngka2.getText());
        double hasil;
        
        int pilih = proses.getSelectedIndex();
        switch(pilih){
            case 1: hasil = input1 * input2; break;
            case 2: 
                if (input2 == 0) {
                    JOptionPane.showMessageDialog(this,"Tidak bisa membagi nol","ERROR", JOptionPane.ERROR_MESSAGE);
                    txtHasil.setText("");
                    return;
                }
                hasil = input1 / input2; break;
            case 3: hasil = input1 + input2; break;
            case 4: hasil = input1 - input2; break;
            default:
                txtHasil.setText("");
                return;
        }
        txtHasil.setText(String.valueOf(hasil));
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Input tidak valid. Masukkan angka!", "ERROR", JOptionPane.ERROR_MESSAGE);
        txtHasil.setText("");
    }
    }//GEN-LAST:event_prosesActionPerformed

